#!/bin/bash
set -euxo pipefail

# ---------------------------------------------------------------------------
# Detect package manager
# ---------------------------------------------------------------------------
set +x
PKG_MANAGER=""
for pm in apt-get zypper dnf yum microdnf apk pacman; do
  if command -v "$pm" >/dev/null 2>&1; then
    PKG_MANAGER="$pm"
    break
  fi
done

if [ -z "$PKG_MANAGER" ]; then
  echo "Error: no supported package manager found" >&2
  exit 1
fi
set -x
echo "Using package manager: $PKG_MANAGER"
# ---------------------------------------------------------------------------

ROOT_DIR="$(realpath "$(dirname "$0")/../..")"
INSTALL_DIR="/srv/vacuula"
BACKUP_DIR="/srv/vacuula-backups"

# Stop service, optionally back up existing data
systemctl stop vacuula 2>/dev/null || true

if [[ -d "$INSTALL_DIR/data" ]]; then
    read -r -p "Back up existing data first? [Y/n] " answer
    if [[ ! "$answer" =~ ^[Nn] ]]; then
        mkdir -p /srv/vacuula-backups
        tar -czf "/srv/vacuula-backups/data-$(date +%Y%m%d-%H%M%S).tar.gz" -C "$INSTALL_DIR" data
        echo "Backup saved to /srv/vacuula-backups"
    fi
fi

# Version detection (from server/pyproject.toml)
detect_version() {
    local default="0.0.0-dev"
    local version

    version="$(sed -nE 's/^version = "(.*)"/\1/p' "$ROOT_DIR/server/pyproject.toml" 2>/dev/null | head -1)"
    version="${version:-$default}"

    # Local changes -> -dirty
    if [[ -n "$(git -C "$ROOT_DIR" status --porcelain 2>/dev/null)" ]]; then
        version="${version}-dirty"
    fi

    echo "$version"
}

NODE_VERSION="${NODE_VERSION:-22.23.3}"
NODE_DIR="/opt/node-build"

install_node() {
    local arch
    case "$(uname -m)" in
        x86_64|amd64)  arch="x64" ;;
        aarch64|arm64) arch="arm64" ;;
        armv7l|armv8l) arch="armv7l" ;;
        *) echo "Unsupported architecture: $(uname -m)" >&2; exit 1 ;;
    esac

    local name="node-v${NODE_VERSION}-linux-${arch}"
    local base="https://nodejs.org/dist/v${NODE_VERSION}"
    local tmp
    tmp="$(mktemp -d)"

    curl -fsSL -o "$tmp/${name}.tar.xz" "$base/${name}.tar.xz"
    curl -fsSL -o "$tmp/SHASUMS256.txt" "$base/SHASUMS256.txt"
    (cd "$tmp" && grep " ${name}.tar.xz\$" SHASUMS256.txt | sha256sum -c -)

    rm -rf "$NODE_DIR"
    mkdir -p "$NODE_DIR"
    tar -xJf "$tmp/${name}.tar.xz" -C "$NODE_DIR" --strip-components=1
    rm -rf "$tmp"

    export PATH="$NODE_DIR/bin:$PATH"
    node --version
}


APP_VERSION="$(detect_version)"
echo "Installing Vacuula version: $APP_VERSION"

sleep 1

install_deps() {
    case "$PKG_MANAGER" in
        apt-get)
            apt-get update
            apt-get install -y --no-install-recommends \
                curl \
                ca-certificates \
                openssl \
                xz-utils \
                uv
            ;;
        dnf)
            dnf -y install \
                curl \
                ca-certificates \
                openssl \
                xz \
                uv
            ;;
        zypper)
            zypper --non-interactive install --no-recommends \
                curl \
                ca-certificates \
                openssl \
                xz \
                uv
            ;;
        yum)
            yum -y install curl ca-certificates openssl xz uv
            ;;
        microdnf)
            microdnf install -y curl ca-certificates openssl xz uv
            ;;
        apk)
            apk add --no-cache curl ca-certificates openssl xz uv
            ;;
        pacman)
            pacman -Sy --noconfirm curl ca-certificates openssl xz uv
            ;;
    esac
}

install_deps

# uv
if ! command -v uv >/dev/null 2>&1; then
    curl -LsSf https://astral.sh/uv/install.sh | UV_UNMANAGED_INSTALL=/usr/local/bin sh
fi

# Service user
if ! id vacuula >/dev/null 2>&1; then
    useradd --system --home-dir "$INSTALL_DIR" --shell /usr/sbin/nologin vacuula
fi

# Frontend
cd "$ROOT_DIR/app"

# install node if needed
if ! command -v node >/dev/null 2>&1; then
    install_node
fi

# corepack should always work?
if command -v corepack >/dev/null 2>&1; then
    corepack enable
else # if not, install it this way
    echo "corepack not found, installing pnpm manually"
    npm install -g pnpm
fi

pnpm approve-builds @parcel/watcher
pnpm install --frozen-lockfile
pnpm vite build

# Install application
mkdir -p "$INSTALL_DIR"

rm -rf "$INSTALL_DIR/src"
rm -rf "$INSTALL_DIR/migrations"
rm -rf "$INSTALL_DIR/web"

cp -r "$ROOT_DIR/server/src" "$INSTALL_DIR/src"
cp -r "$ROOT_DIR/server/migrations" "$INSTALL_DIR/migrations"
cp "$ROOT_DIR/server/alembic.ini" "$INSTALL_DIR/alembic.ini"

# Build version
cat > "$INSTALL_DIR/src/vacuula_server/_build_version.py" <<EOF
APP_VERSION = "${APP_VERSION}" # version is auto-generated by install script
EOF

# Python project files
cp "$ROOT_DIR/server/pyproject.toml" \
   "$ROOT_DIR/server/uv.lock" \
   "$INSTALL_DIR/"

mkdir -p "$INSTALL_DIR/ssl"
cp "$ROOT_DIR/server/ssl/vacuula.cnf" "$INSTALL_DIR/ssl/vacuula.cnf"

cp -r "$ROOT_DIR/app/dist" "$INSTALL_DIR/web"

# Python dependencies
export UV_PYTHON_INSTALL_DIR=/opt/uv-python
cd "$INSTALL_DIR"
uv sync --frozen --no-dev --no-editable --reinstall-package vacuula-server

# Install systemd service
cp "$ROOT_DIR/build/lxc/vacuula.service" /etc/systemd/system/vacuula.service

systemctl daemon-reload
systemctl enable vacuula

# Data
cd "$INSTALL_DIR"
mkdir -p "$INSTALL_DIR/data"

.venv/bin/alembic upgrade head
chown -R vacuula:vacuula "$INSTALL_DIR/data"

# Start
systemctl restart vacuula

echo "Vacuula ${APP_VERSION} installed. Check status with: systemctl status vacuula and logs with: journalctl -u vacuula -f"